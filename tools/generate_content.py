"""Generate typed definitions only from explicit original lists and UI names."""
from pathlib import Path
import hashlib
import json
from asset_paths import ROOT, asset_manifest, runtime_path
from workspace_budget import check_budget

IDS = ['Hands', 'Pistol', 'Axe', 'Smg', 'Bow', 'Grenade', 'Shotgun', 'Sniper',
       'PetCube', 'RocketLauncher', 'Shurikens', 'Knife', 'Shield', 'MachineGun',
       'AssaultRifle', 'HeavyPistol', 'Katana', 'SemiAutoRifle', 'LightSmg', 'Taser',
       'MedicGun', 'Medkit', 'Nunchaku', 'SmokeBomb', 'Flamethrower', 'Helicopter']


def main():
    check_budget(1_000_000)
    source = ROOT / 'scratch/original/project.json'
    project = json.loads(source.read_text(encoding='utf-8'))
    lists = {value[0]: (key, value[1]) for key, value in project['targets'][0]['lists'].items()}
    labels = {item['code']: item for item in json.loads((ROOT / 'scratch/items.json').read_text(encoding='utf-8'))}
    manifest = asset_manifest()
    ui = next(target for target in project['targets'] if target['name'] == '[UI]')
    modes = next(target for target in project['targets'] if target['name'] == '[GAME UI]')['costumes']
    quote = lambda value: json.dumps(value, ensure_ascii=True)
    rows = []
    for index, code in enumerate(lists['ITEMS'][1]):
        assert code == (chr(ord('a') + index) if index < 25 else 'heli')
        category = 'Vehicle' if code == 'heli' else next(name for name, original in [('Primary', '.Primary weapons'), ('Secondary', '.Secondary weapons'), ('Gadget', '.Gadgets')] if code in lists[original][1])
        gear = lists['Gear points'][1][index] if index < len(lists['Gear points'][1]) else ''
        reload = lists['Reload Speed'][1][index] if index < len(lists['Reload Speed'][1]) else ''
        icon = next((asset for asset in ui['costumes'] if asset['name'] == code + '_item'), None)
        references = [f'Stage/lists/{lists["ITEMS"][0]}[{index+1}]']
        if gear != '': references.append(f'Stage/lists/{lists["Gear points"][0]}[{index+1}]')
        if reload != '': references.append(f'Stage/lists/{lists["Reload Speed"][0]}[{index+1}]')
        rows.append('    {ItemId::' + IDS[index] + ', ' + quote(code) + ', ' + quote(labels[code]['name'].strip() if labels[code]['name'] else 'Helicopter') + ', ItemCategory::' + category + ', ' + (str(int(gear)) if gear != '' else 'std::nullopt') + ', ' + (str(float(reload)) if reload != '' else 'std::nullopt') + ', ' + quote(runtime_path(icon, manifest) if icon else '') + ', ' + quote('; '.join(references)) + '},')
    rows = ['    {\n        ' + row.strip()[1:-2].replace(', ', ',\n        ') + '\n    },' for row in rows]
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    text = '// Generated by tools/generate_content.py; edit the generator, not this file.\n#pragma once\n#include "content.hpp"\n#include <array>\n\nnamespace bb::content::generated {\n'
    text += f'inline constexpr std::string_view sourceSha256 = "{digest}";\n'
    text += 'inline constexpr std::array<ItemDefinition, 26> items{{\n' + '\n'.join(rows) + '\n}};\n'
    text += 'inline constexpr std::array<MatchDefinition, 4> matches{{\n'
    for mode, name in [('TeamDeathmatch', 'Team Death Match'), ('GunGame', 'Gun game'), ('CaptureTheFlag', 'Capture the flag'), ('FreeForAll', 'Free for all')]:
        index = next(i for i, costume in enumerate(modes) if costume['name'] == name)
        text += f'    {{MatchMode::{mode}, {quote(name)}, "[GAME UI]/costumes/{index}"}},\n'
    text += '}};\n}\n'
    (ROOT / 'src/generated_content.hpp').write_text(text, encoding='utf-8')
    print('Generated 26 typed items and 4 match modes from original source lists.')


if __name__ == '__main__':
    main()
